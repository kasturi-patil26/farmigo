export function findCropByName(query: string): CropDefinition {
  if (!query) return CROP_LIST[0];
  const q = query.toLowerCase().trim();
  
  // Exact name or canonical match
  const exact = CROP_LIST.find(
    (c) => c.name.toLowerCase() === q || c.canonicalName.toLowerCase() === q || c.id === q
  );
  if (exact) return exact;

  // Substring match
  const sub = CROP_LIST.find(
    (c) =>
      q.includes(c.canonicalName.toLowerCase()) ||
      c.name.toLowerCase().includes(q) ||
      q.includes(c.marathiName.toLowerCase()) ||
      q.includes(c.hindiName.toLowerCase())
  );
  if (sub) return sub;

  return CROP_LIST[0];
}

export function getAllCropNames(): string[] {
  return CROP_LIST.map((c) => c.name);
}

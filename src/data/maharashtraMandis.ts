export function getMandiById(id: string): APMCMandi | undefined {
  return MAHARASHTRA_MANDIS.find((m) => m.id === id);
}

export function getMandisByDistrict(district: string): APMCMandi[] {
  if (!district || district === 'All') return MAHARASHTRA_MANDIS;
  return MAHARASHTRA_MANDIS.filter((m) => m.district.toLowerCase() === district.toLowerCase());
}

export function getAllDistricts(): string[] {
  const set = new Set<string>();
  MAHARASHTRA_MANDIS.forEach((m) => set.add(m.district));
  return Array.from(set).sort();
}
